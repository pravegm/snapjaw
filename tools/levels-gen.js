#!/usr/bin/env node
// Writes Snap/Core/LevelData.swift from tools/levels.js (R8, ROUND-8 §4). Run after any level change:
//   node tools/levels-gen.js
// then `node tools/balance-sim.js levels=1` to check every level is still winnable.
'use strict';
const fs = require('fs');
const path = require('path');
const { LEVELS, goalOf } = require('./levels.js');

const num = (x) => {
  const s = String(x);
  return s.includes('.') || s.includes('e') ? s : s + '.0';
};
const str = (s) => '"' + String(s).replace(/\\/g, '\\\\').replace(/"/g, '\\"') + '"';

const lines = [];
lines.push('import Foundation');
lines.push('');
lines.push('// GENERATED by tools/levels-gen.js from tools/levels.js. Do not edit by hand: edit tools/levels.js, run');
lines.push('// `node tools/levels-gen.js`, then `node tools/balance-sim.js levels=1`.');
lines.push('');
lines.push('extension LevelBook {');
lines.push('    /// The 30 levels (R8, ROUND-8 §4), in order: 1–10 Morning Bog, 11–20 Dusk, 21–30 Night.');
lines.push('    static let all: [LevelSpec] = [');
for (const L of LEVELS) {
  const g = goalOf(L);
  const species = '[' + g.species.map((s) => '.' + s).join(', ') + ']';
  lines.push(`        LevelSpec(id: ${L.id}, world: ${L.world}, title: ${str(L.title)}, goalText: ${str(L.goalText)},`);
  lines.push(`                  goal: LevelGoal(catchAny: ${g.catchAny}, species: ${species}, speciesCount: ${g.speciesCount}, biteOf: ${g.biteOf}, spare: ${g.spare}),`);
  lines.push(`                  noSting: ${L.noSting ? 'true' : 'false'}, biteLimit: ${L.bites == null ? 'nil' : L.bites}, timeLimit: ${L.time == null ? 'nil' : num(L.time)},`);
  lines.push(`                  twoStarBites: ${L.stars[0]}, threeStarBites: ${L.stars[1]}, cleanForThree: ${L.clean3 ? 'true' : 'false'}, paceWave: ${L.pace},`);
  lines.push('                  bugs: [');
  for (const b of L.bugs) {
    lines.push(`                    LevelBug(.${b.s}, at: ${num(b.at)}, u: ${num(b.u)}, v: ${num(b.v)}, linger: ${num(b.linger)}, sip: ${b.sip ? 'true' : 'false'}),`);
  }
  lines.push('                  ]),');
}
lines.push('    ]');
lines.push('}');
lines.push('');
const out = path.join(__dirname, '..', 'Snap', 'Core', 'LevelData.swift');
fs.writeFileSync(out, lines.join('\n'));
console.log(`wrote ${out}: ${LEVELS.length} levels`);
